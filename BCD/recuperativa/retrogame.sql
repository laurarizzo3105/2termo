USE REC_RETROGAME_LAURA31;

CREATE TABLE CLIENTE (
    ID_CLIENTE INT AUTO INCREMENT PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20) NULL,
    ATIVO BOOLEAN DEFAULT TRUE,
);

CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT AUTO INCREMENT PRIMARY KEY,
    NOME VARCHAR(80) NOT NULL,
);

CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT PK AUTO INCREMENT,
    DESCRICAO VARCHAR(80) NOT NULL UNIQUE,
);

CREATE TABLE JOGO (
    ID_JOGO INT PK AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    CODIGO VARCHAR(15) NOT NULL UNIQUE,
    ANO_LANCAMENTO INT NOT NULL,
    ANO_PUBLICADO INT,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK >=0,
    ID_PLATAFORMA INT FK
    ID_CATEGORIA INT FK
);

CREATE TABLE LOCACAO (
    ID_LOCACAO INT PK AUTO_INCREMENT,
    DATA_RETIRADA DATETIME,
    CODIGO VARCHAR(15) NOT NULL UNIQUE,
    ANO_LANCAMENTO INT NOT NULL,
    ANO_PUBLICADO INT,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK >=0,
    ID_PLATAFORMA INT FK
    ID_CATEGORIA INT FK
);


